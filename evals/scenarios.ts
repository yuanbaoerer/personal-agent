export const SCENARIO_COUNTS: Record<ScenarioCategory, number> = {
  channel: 8,
  task: 10,
  permission: 10,
  recovery: 8,
  memory: 4,
};

export function validateCatalog(): string[] {
  const errors: string[] = [];
  if (SCENARIOS.length !== 40) {
    errors.push(`expected 40 scenarios, found ${SCENARIOS.length}`);
  }
  const ids = new Set<string>();
  for (const scenario of SCENARIOS) {
    if (ids.has(scenario.id)) {
      errors.push(`duplicate scenario id ${scenario.id}`);
    }
    ids.add(scenario.id);
    if (scenario.test === undefined && scenario.pending === undefined) {
      errors.push(`${scenario.id} has neither a test nor a pending reason`);
    }
    if (scenario.test !== undefined && scenario.pending !== undefined) {
      errors.push(`${scenario.id} has both a test and a pending reason`);
    }
  }
  for (const [category, count] of Object.entries(SCENARIO_COUNTS)) {
    const actual = SCENARIOS.filter((scenario) => scenario.category === category).length;
    if (actual !== count) {
      errors.push(`category ${category}: expected ${count}, found ${actual}`);
    }
  }
  return errors;
}
